# AForge-style C# file representing a real legacy source file with complex syntax constructs.
AFORGE_LEGACY_CS = """// <auto-generated />
// AForge Image Processing Library
// http://www.aforgenet.com/framework/
//
// Copyright © AForge.NET, 2005-2011
// contacts@aforgenet.com
//

using System;
using System.Diagnostics;

namespace AForge.Imaging.Filters
{
    /// <summary>
    /// Legacy AForge example processing filter mimicking real source constructs.
    /// </summary>
    [Serializable]
    [Obsolete("Use modern filters instead")]
    public class LegacyFilter
    {
        #region Fields & Properties
        private string filterName = "AForge Legacy Filter";
        public string FilterName
        {
            get { return this.filterName; }
        }
        #endregion

        #region Public Methods
        public void ProcessImage(byte[] pixelData)
        {
            // Inline comment inside method
            Debug.WriteLine("Processing image: " + this.FilterName);

            LegacyFilter.NestedHelper helper = new LegacyFilter.NestedHelper();
            string msg = helper.GetStatus();
            Console.WriteLine("Helper status: " + msg);
        }
        #endregion

        /// <summary>
        /// Nested helper class to test preservation of nested types.
        /// </summary>
        public class NestedHelper
        {
            public string GetStatus()
            {
                return "Ready";
            }
        }
    }
}
"""

AFORGE_CSPROJ = """<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <TargetFramework>net452</TargetFramework>
    <Nullable>disable</Nullable>
  </PropertyGroup>
</Project>
"""

def test_aforge_preservation_recipe_conversion(tmp_path: Path):
    cs_file = tmp_path / "LegacyFilter.cs"
    csproj_file = tmp_path / "AForge.Imaging.Filters.csproj"
    
    cs_file.write_text(AFORGE_LEGACY_CS, encoding="utf-8")
    csproj_file.write_text(AFORGE_CSPROJ, encoding="utf-8")
    
    # 1. Run cs-file-scoped-namespace recipe
    res_ns = run_recipe("cs-file-scoped-namespace", "ns-conv", str(tmp_path), dry_run=False)
    assert res_ns.status == "EXECUTED"
    
    final_cs = cs_file.read_text(encoding="utf-8")
    
    # Assert structural conversion worked
    assert "namespace AForge.Imaging.Filters;" in final_cs
    
    # Assert strict preservation of comments, regions, attributes, strings, nested classes, and members
    assert "// <auto-generated />" in final_cs
    assert "// AForge Image Processing Library" in final_cs
    assert "/// <summary>" in final_cs
    assert "[Serializable]" in final_cs
    assert '[Obsolete("Use modern filters instead")]' in final_cs
    assert '#region Fields & Properties' in final_cs
    assert 'private string filterName = "AForge Legacy Filter";' in final_cs
    assert 'Debug.WriteLine("Processing image: " + this.FilterName);' in final_cs
    assert 'LegacyFilter.NestedHelper helper = new LegacyFilter.NestedHelper();' in final_cs
    assert 'public class NestedHelper' in final_cs
    assert '#endregion' in final_cs


