    cs_file = tmp_path / "LegacyFilter.cs"
    csproj_file = tmp_path / "fail_build.csproj"  # triggers compile/validation failure
    
    cs_file.write_text(AFORGE_LEGACY_CS, encoding="utf-8")
    csproj_file.write_text(AFORGE_CSPROJ, encoding="utf-8")
    
