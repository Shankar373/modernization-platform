# ── Regression Tests for Code Cleanup & Optimization Stage ───────────────────────

def test_aforge_optimization_and_cleanup_preservation(tmp_path: Path):
    from app.optimization.optimizer import CodeOptimizer, _make_unified_diff
    from app.core.domain.models import FileChangeMetadata

    # Setup source file and project file mimicking AForge legacy structure
    cs_file = tmp_path / "LegacyFilter.cs"
    csproj_file = tmp_path / "AForge.Imaging.Filters.csproj"
    
    cs_file.write_text(AFORGE_LEGACY_CS, encoding="utf-8")
    csproj_file.write_text(AFORGE_CSPROJ, encoding="utf-8")

    # 1. Run modernization recipe (namespace upgrade)
    res_ns = run_recipe("cs-file-scoped-namespace", "ns-conv", str(tmp_path), dry_run=False)
    assert res_ns.status == "EXECUTED"
    
    modernized_content = cs_file.read_text(encoding="utf-8")
    assert "namespace AForge.Imaging.Filters;" in modernized_content
    
    # Check that comments, regions, member-access before optimization are correct
    assert "// Inline comment inside method" in modernized_content
    assert "#region Fields & Properties" in modernized_content
    assert "LegacyFilter.NestedHelper helper" in modernized_content

    # 2. Run CodeOptimizer on the modernized file
    optimizer = CodeOptimizer()
    
    # Create FileChangeMetadata representing the modernization result
    item = FileChangeMetadata(
        file="LegacyFilter.cs",
        status="MODIFIED",
        before_content=AFORGE_LEGACY_CS,
        after_content=modernized_content,
        diff=_make_unified_diff(AFORGE_LEGACY_CS, modernized_content, "LegacyFilter.cs")
    )
    
    # Run optimizer in apply mode
    opt_result = optimizer.optimize(str(tmp_path), [item], dry_run=False)
    
    assert opt_result.success is True
    assert opt_result.rolled_back is False
    assert opt_result.build_passed is True

    # 3. Verify optimized content preserves all requested properties
    optimized_content = cs_file.read_text(encoding="utf-8")
    
    # Modernization namespace change must remain intact
    assert "namespace AForge.Imaging.Filters;" in optimized_content
    
    # Comments, strings, and attributes must be preserved
    assert "// <auto-generated />" in optimized_content
    assert "// AForge Image Processing Library" in optimized_content
    assert "// Inline comment inside method" in optimized_content
    assert "[Serializable]" in optimized_content
    assert '[Obsolete("Use modern filters instead")]' in optimized_content
    assert 'private string filterName = "AForge Legacy Filter";' in optimized_content
    assert 'Debug.WriteLine("Processing image: " + this.FilterName);' in optimized_content
    
    # Regions must be preserved
    assert "#region Fields & Properties" in optimized_content
    assert "#region Public Methods" in optimized_content
    assert "#endregion" in optimized_content
    
    # Member access . must be preserved
    assert "LegacyFilter.NestedHelper helper = new LegacyFilter.NestedHelper();" in optimized_content
    assert "string msg = helper.GetStatus();" in optimized_content

    # Traceability diffs verification
    opt_file = opt_result.optimized_files[0]
    assert opt_file.original_content == AFORGE_LEGACY_CS
    assert opt_file.modernized_content == modernized_content
    assert opt_file.optimized_content == optimized_content
    
    # Diffs must be real and non-empty for modernization
    assert "namespace AForge.Imaging.Filters;" in opt_file.modernization_diff
    # Optimization diff represents format changes (e.g. dotnet format removing block brace)
    if opt_file.changed:
        assert opt_file.optimization_diff != ""
        assert "a/LegacyFilter.cs" in opt_file.final_diff
    else:
        assert opt_file.optimization_diff == ""


def test_aforge_optimization_rollback_independent_of_modernization(tmp_path: Path):
    from app.optimization.optimizer import CodeOptimizer, _make_unified_diff
    from app.core.domain.models import FileChangeMetadata

    cs_file = tmp_path / "LegacyFilter.cs"
    csproj_file = tmp_path / "fail_build.csproj"  # triggers validation/build failure after optimization
    
    cs_file.write_text(AFORGE_LEGACY_CS, encoding="utf-8")
    csproj_file.write_text(AFORGE_CSPROJ, encoding="utf-8")

    # 1. Run modernization recipe (namespace upgrade) with normal csproj first so it passes
    # We rename csproj temporarily to let recipe execution pass validation
    normal_csproj = tmp_path / "AForge.Imaging.Filters.csproj"
    normal_csproj.write_text(AFORGE_CSPROJ, encoding="utf-8")
    
    res_ns = run_recipe("cs-file-scoped-namespace", "ns-conv", str(tmp_path), dry_run=False)
    assert res_ns.status == "EXECUTED"
    modernized_content = cs_file.read_text(encoding="utf-8")
    
    # Remove normal csproj to activate fail_build.csproj
    normal_csproj.unlink()
    
    # 2. Run CodeOptimizer. The dotnet build will fail because of fail_build.csproj
    optimizer = CodeOptimizer()
    item = FileChangeMetadata(
        file="LegacyFilter.cs",
        status="MODIFIED",
        before_content=AFORGE_LEGACY_CS,
        after_content=modernized_content,
        diff=""
    )
    
    opt_result = optimizer.optimize(str(tmp_path), [item], dry_run=False)
    
    # Assert optimization failed and was rolled back
    assert opt_result.success is False
    assert opt_result.rolled_back is True
    assert opt_result.build_passed is False
    
    # Assert optimization rollback is independent: modernized namespace content remains intact,
    # but the optimized formatter changes were rolled back!
    current_content = cs_file.read_text(encoding="utf-8")
    assert "namespace AForge.Imaging.Filters;" in current_content, (
        "Modernization changes (file-scoped namespace) must remain intact after optimization rollback"
    )


